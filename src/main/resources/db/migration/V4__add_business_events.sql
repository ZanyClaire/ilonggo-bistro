-- Business Events & Multi-Photo Albums (Admin & Guest Uploads)

CREATE TABLE business_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    slug VARCHAR(180) NOT NULL UNIQUE,
    event_type VARCHAR(60) NOT NULL,
    event_date DATE NOT NULL,
    location VARCHAR(200) NOT NULL,
    description TEXT,
    cover_image_url VARCHAR(500),
    allow_guest_uploads BOOLEAN NOT NULL DEFAULT TRUE,
    is_published BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_business_events_type_date ON business_events(event_type, event_date DESC);

CREATE TABLE event_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    image_url VARCHAR(500) NOT NULL,
    caption VARCHAR(255),
    uploaded_by VARCHAR(120) NOT NULL,
    uploader_role VARCHAR(20) NOT NULL DEFAULT 'ADMIN',
    approved BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INT NOT NULL DEFAULT 0,
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_event_photos_event FOREIGN KEY (event_id) REFERENCES business_events(id) ON DELETE CASCADE
);

CREATE INDEX idx_event_photos_event_approved ON event_photos(event_id, approved);

