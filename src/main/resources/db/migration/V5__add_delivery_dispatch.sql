-- On-Demand Rider Delivery Dispatch & Tracking

ALTER TABLE pos_orders ADD COLUMN delivery_fee_php NUMERIC(10, 2) NOT NULL DEFAULT 0.00;
ALTER TABLE pos_orders ADD COLUMN payment_status VARCHAR(24) NOT NULL DEFAULT 'PAID';

CREATE TABLE deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE,
    provider VARCHAR(30) NOT NULL,
    external_delivery_id VARCHAR(120),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING_DISPATCH',
    pickup_address VARCHAR(255) NOT NULL,
    pickup_lat DOUBLE PRECISION NOT NULL,
    pickup_lng DOUBLE PRECISION NOT NULL,
    dropoff_address VARCHAR(300) NOT NULL,
    dropoff_landmark VARCHAR(255),
    dropoff_lat DOUBLE PRECISION NOT NULL,
    dropoff_lng DOUBLE PRECISION NOT NULL,
    distance_km NUMERIC(6, 2) NOT NULL,
    delivery_fee_php NUMERIC(10, 2) NOT NULL,
    estimated_minutes INT NOT NULL DEFAULT 30,
    rider_name VARCHAR(120),
    rider_phone VARCHAR(40),
    rider_plate_number VARCHAR(40),
    tracking_url VARCHAR(500),
    fallback_reason VARCHAR(255),
    last_webhook_payload TEXT,
    dispatched_at TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_deliveries_order FOREIGN KEY (order_id) REFERENCES pos_orders(id) ON DELETE CASCADE
);

CREATE INDEX idx_deliveries_status ON deliveries(status);
CREATE INDEX idx_deliveries_external_id ON deliveries(external_delivery_id);
