-- POS Orders, Line Items & Customer Purchase History

CREATE TABLE pos_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number VARCHAR(28) NOT NULL UNIQUE,
    customer_name VARCHAR(120) NOT NULL,
    customer_phone VARCHAR(30),
    order_type VARCHAR(24) NOT NULL DEFAULT 'DINE_IN',
    table_number VARCHAR(30),
    payment_method VARCHAR(24) NOT NULL DEFAULT 'CASH',
    subtotal_php NUMERIC(10, 2) NOT NULL,
    discount_label VARCHAR(60),
    discount_php NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    total_php NUMERIC(10, 2) NOT NULL,
    amount_tendered_php NUMERIC(10, 2) NOT NULL,
    change_php NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    status VARCHAR(20) NOT NULL DEFAULT 'PAID',
    cashier_username VARCHAR(80) NOT NULL,
    notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_pos_orders_created ON pos_orders(created_at DESC);
CREATE INDEX idx_pos_orders_customer ON pos_orders(customer_name);
CREATE INDEX idx_pos_orders_status ON pos_orders(status);

CREATE TABLE pos_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    menu_item_id BIGINT,
    item_name VARCHAR(140) NOT NULL,
    unit_price_php NUMERIC(10, 2) NOT NULL,
    quantity INT NOT NULL,
    line_total_php NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_pos_items_order FOREIGN KEY (order_id) REFERENCES pos_orders(id) ON DELETE CASCADE,
    CONSTRAINT fk_pos_items_menu FOREIGN KEY (menu_item_id) REFERENCES menu_items(id) ON DELETE SET NULL
);

CREATE INDEX idx_pos_order_items_order ON pos_order_items(order_id);
